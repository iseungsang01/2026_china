def R7(P, o=None, var=""):
    """확정 항공편 기준 — 8/10 PEK 14:00 도착 / 8/14 10:40 출발.
    도착일 저녁이 천단 경점(17:30 마감) 또는 징산 만춘정(18:00 마감)이라
    입국·이동 지연이 그대로 여기서 드러난다."""
    I = []
    ARR, DEP = M("14:00"), M("10:40")
    for e in P:
        if e["d"] != "8/10" or e["k"] != "activity":
            continue
        if "천단 관람" in e["lab"]:
            last, close, nm = TIANTAN_ENTRY_LAST, TIANTAN_CLOSE, "천단 경점"
        elif "만춘정" in e["lab"]:
            last, close, nm = WANCHUN_LAST, JINGSHAN[1], "징산 만춘정"
        else:
            continue
        chain = e["t"] - ARR
        if e["t"] > last:
            I.append("%s 도착 %s — 입장 마감 %s 초과 (입국·이동 %d분)"
                     % (nm, HM(e["t"]), HM(last), chain))
        else:
            NOTES.append("%s 도착 %s / 한계 도착시각 %s → 여유 %d분 (폐문 %s까지 %d분)"
                         % (nm, HM(e["t"]), HM(last - chain), last - chain - ARR,
                            HM(close), close - e["t"]))
    # 출국일: 국제선 2시간 전 도착 필요
    need = DEP - 120
    for e in P:
        if e["d"] == "8/14" and "공항" in e["lab"] and e["k"] == "move":
            arr = e["t"] + e["dur"]
            if arr > need:
                I.append("공항 도착 %s — 출발 2시간 전(%s)보다 늦음" % (HM(arr), HM(need)))
            else:
                NOTES.append("공항 도착 %s / 마지노선 %s → 여유 %d분"
                             % (HM(arr), HM(need), need - arr))
    return I


